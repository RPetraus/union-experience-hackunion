  if (location.startsWith("Lippman")) return "lippman-hall";
  if (location.startsWith("ISEC")) return "isec-building";
  if (location.startsWith("Olin")) return "olin-center";
  if (location.startsWith("Wold")) return "wold-center";
  if (location.startsWith("Sorum")) return "sorum-house";
  if (location.startsWith("Language Center")) return "language-center";
  if (location.startsWith("Old Chapel")) return "old-chapel";
  if (location.startsWith("Schaffer Library")) return "schaffer-library";
  if (location.startsWith("Wicker Wellness Center")) return "wicker-health";
  if (location.startsWith("Yulman Theater")) return "yulman-theater";
  if (location.startsWith("Nott Memorial")) return "nott-events";
  if (location.startsWith("West College")) return "west-social-space";
  if (location.startsWith("West Social Space")) return "west-social-space";
  if (location.startsWith("West Beach Lawn")) return "west-beach-lawn";
  if (location.startsWith("Lower Aerobics Room")) return "alumni-gym";
  if (location.startsWith("Reamer")) return "reamer-campus-center";
  if (location.startsWith("Kenney Center")) return "kenney-center";
